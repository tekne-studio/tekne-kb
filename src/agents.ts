import { spawnSync } from 'node:child_process';
import { existsSync, lstatSync, readdirSync, readFileSync, readlinkSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { type Config, CONFIG_FILE, type Ctx, type Problem } from './config';
import { version } from '../package.json';

// AGENTS.md is the instruction file every agent reads (Codex and Kimi load only it);
// CLAUDE.md is a symlink to it. The shared rules come from kb's templates, between
// markers, so `kb gen` (or any kb command that writes) brings each project up to the
// installed version.
const TEMPLATES = fileURLToPath(new URL('../templates/agents/', import.meta.url));
const OPEN = /<!-- kb:global[^>]*-->/;
// The opener says it itself, for whoever opens the file without knowing kb, and names
// the version that wrote the block, so a stale one shows which rules it carries.
export const OPENER = `<!-- kb:global · generated by kb ${version} -->`;
const CLOSE = '<!-- /kb:global -->';

const hasModule = (m: string) => existsSync(join(TEMPLATES, `${m}.md`));
// rules another tool of the studio keeps
const ELSEWHERE: Record<string, string> = { worktrees: "parallel agents in worktrees are @tekne/wf's (bun add -d @tekne/wf, then bun wf init)" };

/** The block from the modules kb has; one it lacks is kb check's to report, so writing never breaks on it. */
export function globalBlock(modules: string[], config?: Config): string {
	const values = ruleValues(config);
	return modules
		.filter(hasModule)
		.map((m) =>
			readFileSync(join(TEMPLATES, `${m}.md`), 'utf8')
				.trim()
				.replace(/\{\{(\w+)\}\}/g, (_, key: string) => {
					if (!(key in values)) throw new Error(`templates/agents/${m}.md: no value for {{${key}}}`);
					return values[key];
				})
		)
		.join('\n\n');
}

/**
 * The project's own names a template cites, so a rule reads `bun run shots` where the project
 * has one; without it, the general words.
 */
function ruleValues(config?: Config): Record<string, string> {
	const manual = config?.manual;
	const roadmap = config?.roadmap ?? { file: 'roadmap.md', now: 'Now', later: 'Later', doneWhen: 'Done when' };
	return {
		page: manual ? `its page in \`${join(config.docs.dir, manual.dir).replace(/\/$/, '')}/\`` : 'its page',
		run: manual?.run ? `\`${manual.run}\`` : 'the script',
		roadmap: `\`${join(config?.docs.dir ?? 'docs', roadmap.file)}\``,
		now: `\`## ${roadmap.now}\``,
		later: `\`## ${roadmap.later}\``,
		doneWhen: `\`**${roadmap.doneWhen}:**\``,
		item: `${roadmap.file}#<item>`
	};
}

export function agentsProblems(ctx: Ctx, mode: 'check' | 'gen'): Problem[] {
	const agents = ctx.config.agents;
	if (!agents) return [];
	const { file } = agents;
	const out = [...symlinkProblems(ctx, file), ...moduleProblems(agents.modules)];
	const path = ctx.path(file);
	if (!existsSync(path)) return [...out, { level: 'error', where: file, message: 'missing' }];
	const text = readFileSync(path, 'utf8');
	const next = withCurrentRules(text, agents.modules, ctx.config);
	if (next === null) out.push({ level: 'error', where: file, message: `shared block missing: add <!-- kb:global --> and ${CLOSE}, then run kb gen` });
	else if (next !== text) {
		if (mode === 'gen') writeFileSync(path, next);
		else out.push({ level: 'error', where: file, message: 'shared block differs from the kb templates (kb gen, or any kb command that writes, updates it)' });
	}
	if (mode === 'check') out.push(...shapeProblems(file, text, agents.budget));
	return out;
}

// A rule is one line: what to do, with a link to the doc section that explains it. A longer
// item is a description, and the project's part grows one paragraph per feature when nothing
// stops it (one project went from 338 to 4,287 words in 73 commits). Size is the guard: it
// catches the shape without judging what a line repeats, which stays with whoever rewrites it.
const ITEM_WORDS = 80;
const GENERATED_OPEN = /<!-- ([\w-]+:[\w-]+)\b[^>]*-->/;
const generatedClose = (name: string) => new RegExp(`<!-- /${name}\\s*-->`);

type Item = { line: number; words: number; text: string };

/**
 * The project's own part of the file (outside every `<!-- tool:block -->…<!-- /tool:block -->`,
 * kb's and any other tool's): a list item over ITEM_WORDS words, and the whole over the budget.
 * The messages read as the task of the cleanup: each names the file, the line and the first words.
 */
export function shapeProblems(file: string, text: string, budget: number): Problem[] {
	const items: Item[] = [];
	let total = 0;
	let open: Item | undefined;
	let generated: RegExp | undefined;
	let fence = false;
	const wordsOf = (line: string) => line.split(/\s+/).filter(Boolean).length;
	text.split('\n').forEach((line, i) => {
		if (generated) {
			if (generated.test(line)) generated = undefined;
			return;
		}
		const opener = line.match(GENERATED_OPEN);
		if (opener) {
			open = undefined;
			const close = generatedClose(opener[1]);
			if (!close.test(line.slice((opener.index ?? 0) + opener[0].length))) generated = close;
			return;
		}
		total += wordsOf(line);
		if (/^\s*(```|~~~)/.test(line)) fence = !fence;
		const item = !fence && line.match(/^\s*[-*] +\S/);
		if (item) {
			open = { line: i + 1, words: wordsOf(line.replace(/^\s*[-*] +/, '')), text: line.replace(/^\s*[-*] +/, '') };
			items.push(open);
		} else if (!line.trim() || (!fence && /^\s*(#|\|)/.test(line))) open = undefined;
		else if (open) {
			open.words += wordsOf(line);
			open.text += ` ${line.trim()}`;
		}
	});
	const first = (item: Item) => {
		const words = item.text.split(/\s+/).filter(Boolean);
		return `"${words.slice(0, 6).join(' ')}${words.length > 6 ? '…' : ''}"`;
	};
	const out: Problem[] = items
		.filter((item) => item.words > ITEM_WORDS)
		.map((item) => ({
			level: 'error',
			where: `${file}:${item.line}`,
			message: `list item of ${item.words} words, over ${ITEM_WORDS}: ${first(item)}. A rule is one line, what to do, with a link to the doc section that explains it; what describes the system moves to that section`
		}));
	if (total > budget) {
		const longest = [...items]
			.sort((a, b) => b.words - a.words)
			.slice(0, 3)
			.map((item) => `line ${item.line} (${item.words} words) ${first(item)}`);
		out.push({
			level: 'error',
			where: file,
			message: `the project's part has ${total} words, over agents.budget ${budget}. Move what describes the system to the topic docs and leave one line per rule, with a link; the longest items: ${longest.join(', ')}`
		});
	}
	return out;
}

function moduleProblems(modules: string[]): Problem[] {
	const known = readdirSync(TEMPLATES)
		.filter((f) => f.endsWith('.md'))
		.map((f) => f.slice(0, -3))
		.sort();
	return modules
		.filter((m) => !hasModule(m))
		.map((m) => ({
			level: 'error',
			where: CONFIG_FILE,
			message: `agents.modules: kb has no module "${m}"${ELSEWHERE[m] ? `: ${ELSEWHERE[m]}` : ` (it has ${known.join(', ')})`}; take it out of agents.modules`
		}));
}

/**
 * Commands that write call it, so a project gets the rules of the kb it installed without
 * running kb gen. True when it rewrote the block; a missing file or marker stays kb check's.
 */
export function refreshRules(ctx: Ctx): boolean {
	const agents = ctx.config.agents;
	if (!agents || !existsSync(ctx.path(agents.file))) return false;
	const path = ctx.path(agents.file);
	const text = readFileSync(path, 'utf8');
	const next = withCurrentRules(text, agents.modules, ctx.config);
	if (next === null || next === text) return false;
	writeFileSync(path, next);
	return true;
}

/** The file with its shared block rebuilt from the templates; null without the markers. */
function withCurrentRules(text: string, modules: string[], config: Config): string | null {
	const open = text.match(OPEN);
	const end = text.indexOf(CLOSE);
	if (!open || end < 0) return null;
	return `${text.slice(0, open.index)}${OPENER}\n${globalBlock(modules, config)}\n${text.slice(end)}`;
}

/** Every folder with an AGENTS.md (or a CLAUDE.md) has both, and CLAUDE.md is a symlink to AGENTS.md. */
export function symlinkProblems(ctx: Ctx, file = 'AGENTS.md'): Problem[] {
	const tracked = spawnSync('git', ['ls-files', '--cached', '--others', '--exclude-standard', `*${file}`, file, '*CLAUDE.md', 'CLAUDE.md'], {
		cwd: ctx.root,
		encoding: 'utf8'
	}).stdout;
	const out: Problem[] = [];
	for (const dir of new Set(tracked.split('\n').filter(Boolean).map((f) => dirname(f)))) {
		const claude = ctx.path(join(dir, 'CLAUDE.md'));
		const where = join(dir, 'CLAUDE.md');
		if (!existsSync(ctx.path(join(dir, file)))) out.push({ level: 'error', where: join(dir, file), message: `missing: the instructions live in ${file}, with CLAUDE.md as a symlink to it` });
		else if (!isLink(claude)) out.push({ level: 'error', where, message: `must be a symlink to ${file} (ln -sf ${file} CLAUDE.md)` });
		else if (readlinkSync(claude) !== file) out.push({ level: 'error', where, message: `points to ${readlinkSync(claude)}, should point to ${file}` });
	}
	return out;
}

function isLink(path: string): boolean {
	try {
		return lstatSync(path).isSymbolicLink();
	} catch {
		return false;
	}
}
